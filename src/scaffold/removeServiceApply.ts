import * as fs from 'fs';
import * as path from 'path';
import {
	extractServiceTypeNames,
	patchApplicationManifestForRemove,
	patchApplicationParametersForRemove,
	patchSfprojRemoveProjectReference,
	patchStartupServicesXmlForRemove,
} from './removeServiceTemplates';
import type { ApplicationProject, ServiceManifest } from '../project/sfprojModel';

export interface GeneratedCsproj {
	csprojPath: string;
	csprojDirectory: string;
}

export interface RemoveServiceResult {
	packageName: string;
	removedDirectory: string;
	applicationManifestPath: string;
	removedParameters: string[];
	removedServiceBlocks: number;
	patchedParameterFiles: string[];
	removedCsprojPath: string | undefined;
	removedCsprojDirectory: string | undefined;
	removedActorInterfacesDirectory: string | undefined;
	removedProjectReference: boolean;
	patchedStartupServicesManifest: string | undefined;
	patchedStartupParameterFiles: string[];
}

/**
 * Pure on-disk apply step for the Remove Service command.
 * Throws on missing project / package; performs the file deletion last so
 * any patch failure leaves the package directory intact for re-run.
 *
 * Cleans up every artifact the Add Service command can produce:
 *   - The `<Service>Pkg/` directory under `ApplicationPackageRoot/`.
 *   - Matching entries in `ApplicationManifest.xml` and per-environment
 *     `ApplicationParameters/*.xml`.
 *   - When the project has a `StartupServices.xml` (1.1.0+ wiring), also
 *     cleans the `<Service>` block + orphan `<Parameter>` declarations from
 *     `StartupServices.xml` and from every `StartupServiceParameters/<env>.xml`.
 *   - For C# kinds: the sibling `<ServiceName>/` folder generated by the
 *     scaffold (plus its `.Interfaces/` sibling for actors), and the matching
 *     `<ProjectReference>` entry in the `.sfproj`. Detection is conservative
 *     (see {@link findGeneratedCsproj}), so user-authored project references
 *     are never touched.
 */
export async function applyRemoveService(project: ApplicationProject, packageName: string): Promise<RemoveServiceResult> {
	if (!project.applicationManifest) throw new Error('Application manifest is missing.');
	const target = findServiceManifest(project, packageName);
	if (!target) throw new Error(`No service-manifest package named '${packageName}' was found in this application.`);
	// Discover service-type names from the package's ServiceManifest.xml so we can identify
	// every <Service> block in the application manifest that needs to go.
	let serviceTypeNames: string[] = [];
	try {
		const smXml = fs.readFileSync(target.path, 'utf8');
		serviceTypeNames = extractServiceTypeNames(smXml);
	} catch {
		// If the on-disk manifest is missing, fall back to no-types — only the import line will be removed.
	}
	const types = new Set(serviceTypeNames);
	// Locate any companion C# project BEFORE patching, so we can resolve its
	// <SfPackageRoot> against the still-present package directory.
	const generatedCsproj = findGeneratedCsproj(project, target.packageDirectory);
	// Patch ApplicationManifest.xml.
	const appManifestPath = project.applicationManifest.path;
	const before = fs.readFileSync(appManifestPath, 'utf8');
	const patch = patchApplicationManifestForRemove(before, target.name, types);
	fs.writeFileSync(appManifestPath, patch.xml, 'utf8');
	// Patch StartupServices.xml when present (1.1.0 wiring) — same <Service>
	// block + parameter cleanup as the application manifest, but without the
	// <ServiceManifestImport> step (StartupServices.xml has none).
	let patchedStartupServicesManifest: string | undefined;
	const startupOrphanParameters = new Set<string>();
	if (project.startupServicesManifest) {
		try {
			const ssBefore = fs.readFileSync(project.startupServicesManifest, 'utf8');
			const ssPatch = patchStartupServicesXmlForRemove(ssBefore, types);
			if (ssPatch.xml !== ssBefore) {
				fs.writeFileSync(project.startupServicesManifest, ssPatch.xml, 'utf8');
				patchedStartupServicesManifest = project.startupServicesManifest;
			}
			for (const name of ssPatch.removedParameters) startupOrphanParameters.add(name);
		} catch {
			// best-effort
		}
	}
	// Patch ApplicationParameters/*.xml.
	const patchedParamFiles: string[] = [];
	for (const paramFile of project.applicationParameters) {
		try {
			const original = fs.readFileSync(paramFile, 'utf8');
			const after = patchApplicationParametersForRemove(original, patch.removedParameters);
			if (after !== original) {
				fs.writeFileSync(paramFile, after, 'utf8');
				patchedParamFiles.push(paramFile);
			}
		} catch {
			// best-effort
		}
	}
	// Patch StartupServiceParameters/*.xml — drop the same parameter names
	// that were orphaned from StartupServices.xml. Falls back to the
	// application-manifest list if the StartupServices manifest was absent
	// (a defensive measure: VS templates keep both files in lockstep).
	const startupParamNames = startupOrphanParameters.size > 0 ? [...startupOrphanParameters] : patch.removedParameters;
	const patchedStartupParameterFiles: string[] = [];
	for (const paramFile of project.startupServiceParameters) {
		try {
			const original = fs.readFileSync(paramFile, 'utf8');
			const after = patchApplicationParametersForRemove(original, startupParamNames);
			if (after !== original) {
				fs.writeFileSync(paramFile, after, 'utf8');
				patchedStartupParameterFiles.push(paramFile);
			}
		} catch {
			// best-effort
		}
	}
	// Strip the matching <ProjectReference> from the .sfproj and delete the C# folder.
	let removedCsprojPath: string | undefined;
	let removedCsprojDirectory: string | undefined;
	let removedActorInterfacesDirectory: string | undefined;
	let removedProjectReference = false;
	if (generatedCsproj) {
		const sfprojDir = path.dirname(project.sfproj.path);
		const sfprojRelToCsproj = path.relative(sfprojDir, generatedCsproj.csprojPath).replace(/\//g, '\\');
		try {
			const sfprojXml = fs.readFileSync(project.sfproj.path, 'utf8');
			const sfPatch = patchSfprojRemoveProjectReference(sfprojXml, sfprojRelToCsproj);
			if (sfPatch.removed) {
				fs.writeFileSync(project.sfproj.path, sfPatch.xml, 'utf8');
				removedProjectReference = true;
			}
		} catch {
			// best-effort
		}
		// For actor hosts, also delete the sibling <Folder>.Interfaces/ project
		// that the scaffold creates next to the host's csproj directory. We
		// detect it via on-disk sibling existence rather than parsing the
		// host csproj — the sibling carries no markers a future user might
		// strip during cleanup.
		const interfacesDir = `${generatedCsproj.csprojDirectory}.Interfaces`;
		if (fs.existsSync(interfacesDir) && fs.statSync(interfacesDir).isDirectory()) {
			try {
				fs.rmSync(interfacesDir, { recursive: true, force: true });
				removedActorInterfacesDirectory = interfacesDir;
			} catch {
				// best-effort
			}
		}
		// Delete the project folder.
		try {
			if (fs.existsSync(generatedCsproj.csprojDirectory)) {
				fs.rmSync(generatedCsproj.csprojDirectory, { recursive: true, force: true });
				removedCsprojPath = generatedCsproj.csprojPath;
				removedCsprojDirectory = generatedCsproj.csprojDirectory;
			}
		} catch {
			// best-effort
		}
	}
	// Delete the package directory last so failures keep the disk recoverable.
	// For C# kinds the package directory lives under <csprojDir>/PackageRoot/
	// and was deleted along with the csproj folder above; this branch handles
	// legacy + guest layouts where the package is at <App>/ApplicationPackageRoot/<Service>Pkg/.
	const removedDirectory = target.packageDirectory;
	if (fs.existsSync(removedDirectory)) {
		fs.rmSync(removedDirectory, { recursive: true, force: true });
	}
	return {
		packageName: target.name,
		removedDirectory,
		applicationManifestPath: appManifestPath,
		removedParameters: patch.removedParameters,
		removedServiceBlocks: patch.removedServiceBlocks,
		patchedParameterFiles: patchedParamFiles,
		removedCsprojPath,
		removedCsprojDirectory,
		removedActorInterfacesDirectory,
		removedProjectReference,
		patchedStartupServicesManifest,
		patchedStartupParameterFiles,
	};
}

/**
 * Finds the service-manifest package by name (case-insensitive). Also accepts
 * the bare service name without the `Pkg` suffix.
 */
export function findServiceManifest(project: ApplicationProject, name: string): ServiceManifest | undefined {
	const lower = name.toLowerCase();
	const exact = project.serviceManifests.find((s) => s.name.toLowerCase() === lower);
	if (exact) return exact;
	// Allow the user to pass the bare service name without the "Pkg" suffix.
	const withSuffix = lower.endsWith('pkg') ? lower : `${lower}pkg`;
	return project.serviceManifests.find((s) => s.name.toLowerCase() === withSuffix);
}

/**
 * Returns the absolute path to the companion `.csproj` (and its containing
 * directory) when one of the `<ProjectReference>` entries in the `.sfproj`
 * matches the package being removed.
 *
 * Detection strategy (1.1.3+ canonical layout):
 *   The companion C# project owns `<csprojDir>/PackageRoot/` whose content is
 *   the package being removed. So we treat the `.csproj` as a match when its
 *   directory's `PackageRoot/` subfolder equals `packageDirectory`.
 *
 * Legacy fallback (1.1.2 and earlier): the .csproj used a `<SfPackageRoot>`
 * property that pointed at `<App>/ApplicationPackageRoot/<Service>Pkg/`. Kept
 * for projects upgraded from prior versions of the extension.
 *
 * User-authored project references that match neither rule are ignored — the
 * cleanup never deletes hand-written code.
 */
export function findGeneratedCsproj(project: ApplicationProject, packageDirectory: string): GeneratedCsproj | undefined {
	const targetNormalized = path.normalize(packageDirectory).toLowerCase();
	for (const ref of project.sfproj.projectReferences) {
		if (!fs.existsSync(ref)) continue;
		const csprojDir = path.dirname(ref);
		// Modern path-based match: <csprojDir>/PackageRoot/ ≡ packageDirectory.
		const physicalPackageRoot = path.normalize(path.join(csprojDir, 'PackageRoot')).toLowerCase();
		if (physicalPackageRoot === targetNormalized) {
			return { csprojPath: ref, csprojDirectory: csprojDir };
		}
		// Legacy fallback: <SfPackageRoot> property pointing at the App-side dir.
		let body: string;
		try {
			body = fs.readFileSync(ref, 'utf8');
		} catch {
			continue;
		}
		if (!/<IsServiceFabricServiceProject>\s*true\s*<\/IsServiceFabricServiceProject>/i.test(body)) continue;
		const match = /<SfPackageRoot>([\s\S]*?)<\/SfPackageRoot>/i.exec(body);
		if (!match) continue;
		const expanded = match[1]
			.replace(/\$\(MSBuildThisFileDirectory\)/gi, csprojDir + path.sep)
			.replace(/\\/g, path.sep)
			.replace(/\//g, path.sep)
			.trim();
		const resolved = path.resolve(csprojDir, expanded);
		if (path.normalize(resolved).toLowerCase() === targetNormalized) {
			return { csprojPath: ref, csprojDirectory: csprojDir };
		}
	}
	return undefined;
}
